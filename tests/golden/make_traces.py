#!/usr/bin/env python3
"""Regenerate the golden traces.

The traces are committed, not generated at test time: a golden test whose fixture is
regenerated by the code under test asserts nothing. Run this only to add a trace or to
deliberately change one, and say which in the commit message.

Geometry comes from adapters/sparkinfer/pin.json where it is real (the recurrent state
shape of Qwen3.8-27B is measured, not invented). Everything else is labelled synthetic in
the trace's own notes field.

`trace_live_c1.json` is NOT written by this script and running it will not regenerate that
file. It was RECORDED from the live SparkInfer adapter with TENSORTRANSIT_TRACE_OUT, so it
carries the runtime's real KV slice sizes (4210688 bytes per attention layer, against the
12582912 this script invents), its real layer count (64 kernels, against 176), and the
measured step traffic. To re-record it, run the cb bench with:

    TENSORTRANSIT=persist TENSORTRANSIT_WINDOW_ATTACH=capture_node \
    TENSORTRANSIT_STREAMED_BYTES_PER_TOKEN=18500000000 \
    TENSORTRANSIT_TRACE_OUT=trace.json TENSORTRANSIT_TRACE_MODEL=Qwen3.8-27B \
    TENSORTRANSIT_TRACE_RUNTIME_COMMIT=<pin.json commit> \
    qwen3_gguf_cb_bench <model> 1 128 64 4096

and keep the notes field, which says which parts are measured.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

LIN_STATE = 3145728      # fp32 Gated-DeltaNet matrix state, bytes per layer
LIN_CONV = 61440         # bf16 causal-convolution window, bytes per layer
N_LAYERS = 64
FULL_ATTN_INTERVAL = 4   # layer L is recurrent iff (L+1) % interval != 0
# 18.5 GB per decode step, measured; spread over the 64 layers as per-layer weight reads.
STEP_TRAFFIC = 18_500_000_000
RECURRENT_LAYERS = [L for L in range(N_LAYERS) if (L + 1) % FULL_ATTN_INTERVAL != 0]
ATTENTION_LAYERS = [L for L in range(N_LAYERS) if (L + 1) % FULL_ATTN_INTERVAL == 0]


def build(path, *, requests, kv_bytes_per_layer, notes, with_kv=True):
    tensors, events = [], []
    next_id = 1

    def tensor(**kw):
        nonlocal next_id
        entry = {"id": next_id, "mutable": False, "request_local": False,
                 "model_global": False, "request_id": -1}
        entry.update(kw)
        tensors.append(entry)
        next_id += 1
        return entry["id"]

    # Per-layer weights. Read once per token, so the wrap edge makes them "reusable" by a
    # cache of unlimited size -- which is true, and is exactly why the capacity-bounded
    # ceiling is the one that matters. The trace records the workload, not the conclusion.
    recurrent_state_bytes = len(RECURRENT_LAYERS) * (LIN_STATE + LIN_CONV) * requests
    kv_bytes = len(ATTENTION_LAYERS) * kv_bytes_per_layer * requests if with_kv else 0
    # KV moves its whole block on the read and one token's worth on the append, so its
    # traffic is block + append -- NOT 2 x block. Modelling the append as a read-modify-write
    # of the whole block would double its traffic and, worse, give it the same bytes-saved-
    # per-byte-held as a recurrent state, which is precisely the quantity the admission rules
    # discriminate on. An inaccuracy there does not make the comparison noisy, it makes it
    # meaningless.
    kv_append = max(kv_bytes_per_layer // 128, 1) if with_kv else 0
    weight_total = STEP_TRAFFIC - 2 * recurrent_state_bytes - kv_bytes - (
        len(ATTENTION_LAYERS) * kv_append * requests if with_kv else 0)
    weight_per_layer = max(weight_total // N_LAYERS, 1)

    weight_ids = [tensor(role="model_weight", bytes=weight_per_layer, model_global=True)
                  for _ in range(N_LAYERS)]

    state_ids, conv_ids, kv_ids = {}, {}, {}
    for request in range(requests):
        for L in RECURRENT_LAYERS:
            state_ids[(request, L)] = tensor(role="recurrent_state", bytes=LIN_STATE,
                                             mutable=True, request_local=True,
                                             request_id=request)
            conv_ids[(request, L)] = tensor(role="recurrent_state", bytes=LIN_CONV,
                                            mutable=True, request_local=True,
                                            request_id=request)
        if with_kv:
            for L in ATTENTION_LAYERS:
                kv_ids[(request, L)] = tensor(role="kv_cache", bytes=kv_bytes_per_layer,
                                              mutable=True, request_local=True,
                                              request_id=request)

    order = 0

    def event(name, uses):
        nonlocal order
        order += 1
        events.append({"kernel_id": order, "name": name, "stream": 0, "order": order,
                       "tensors": uses})

    for L in range(N_LAYERS):
        event(f"proj_{L}", [{"id": weight_ids[L], "access": "read"}])
        if (L + 1) % FULL_ATTN_INTERVAL != 0:
            for request in range(requests):
                event(f"gdn_conv_{L}_r{request}",
                      [{"id": conv_ids[(request, L)], "access": "read_write"}])
                event(f"gdn_state_{L}_r{request}",
                      [{"id": state_ids[(request, L)], "access": "read_write"}])
        elif with_kv:
            for request in range(requests):
                # The attention read of the whole block, then the append of this token's
                # key/value. Two uses of one tensor at one kernel, which is what the runtime
                # actually does.
                event(f"attn_{L}_r{request}",
                      [{"id": kv_ids[(request, L)], "access": "read"},
                       {"id": kv_ids[(request, L)], "access": "write",
                        "bytes": kv_append}])

    document = {
        "schema_version": 1,
        "device": 0,
        "device_name": "NVIDIA GeForce RTX 5090",
        "model": "Qwen3.8-27B",
        "model_digest": "",
        "runtime": "SparkInfer",
        "runtime_commit": "5347b27cbc43af7281d2ac7b30f41d610514d8f3",
        "phase": "decode",
        "active_requests": requests,
        "cyclic": True,
        "notes": notes,
        "tensors": tensors,
        "events": events,
    }
    with open(path, "w") as handle:
        json.dump(document, handle, indent=1)
        handle.write("\n")
    print(f"{os.path.basename(path)}: {len(tensors)} tensors, {len(events)} kernels")


def main():
    build(os.path.join(HERE, "trace_recurrent.json"), requests=1, kv_bytes_per_layer=0,
          with_kv=False,
          notes="One decode token, recurrent layers only. Recurrent state shape is the "
                "measured Qwen3.8-27B geometry; the per-layer weight reads are the measured "
                "18.5 GB step traffic divided evenly, which is synthetic.")
    build(os.path.join(HERE, "trace_recurrent_kv.json"), requests=1,
          kv_bytes_per_layer=12 * 1024 * 1024,
          notes="One decode token, both tensor classes. KV block size is SYNTHETIC (12 MiB "
                "per attention layer); the recurrent geometry and the step traffic are "
                "measured. This is the trace the multi-tensor arms are compared on.")
    build(os.path.join(HERE, "trace_concurrency.json"), requests=4,
          kv_bytes_per_layer=12 * 1024 * 1024,
          notes="Four concurrent requests, both tensor classes. Request-local state scales "
                "with concurrency and the weight stream does not, which is the whole reason "
                "the locality question changes shape here. Sizes as in trace_recurrent_kv.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
